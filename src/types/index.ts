export interface Student {
  id: string;
  firstName: string;
  lastName: string;
  email: string;
  phone: string;
  level: string;
  notes: string;
  password: string;
  createdAt: string;
  archived: boolean;
}

export interface Appointment {
  id: string;
  studentId: string;
  date: string;
  time: string;
  duration: number;
  subject: string;
  status: 'pending' | 'confirmed' | 'cancelled' | 'completed';
  notes: string;
  price: number;
  paid: boolean;
  createdAt: string;
  archived: boolean;
  purchaseOrderId?: string;
  invoiceId?: string;
}

export interface Invoice {
  id: string;
  number: string;
  studentId: string;
  appointmentIds: string[];
  date: string;
  dueDate: string;
  items: InvoiceItem[];
  total: number;
  status: 'draft' | 'sent' | 'paid' | 'overdue';
  createdAt: string;
  autoGenerated?: boolean;
}

export interface InvoiceItem {
  description: string;
  quantity: number;
  unitPrice: number;
  total: number;
}

export interface PurchaseOrder {
  id: string;
  number: string;
  studentId: string;
  date: string;
  items: InvoiceItem[];
  total: number;
  status: 'pending' | 'approved' | 'rejected';
  createdAt: string;
  appointmentId?: string;
  autoGenerated?: boolean;
}

export interface Document {
  id: string;
  studentId: string;
  name: string;
  type: 'homework' | 'course' | 'exam' | 'other';
  uploadedBy: 'student' | 'teacher';
  size: number;
  dataUrl: string;
  createdAt: string;
}

